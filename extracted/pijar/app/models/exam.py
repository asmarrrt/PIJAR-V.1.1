from datetime import datetime,timezone
from ..extensions import db

class Exam(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    teacher_id=db.Column(db.Integer,db.ForeignKey("user.id"),nullable=False,index=True)
    title=db.Column(db.String(200),nullable=False)
    description=db.Column(db.Text,default="")
    subject=db.Column(db.String(120),nullable=False)
    class_group=db.Column(db.String(120),default="")
    duration_minutes=db.Column(db.Integer,nullable=False)
    starts_at=db.Column(db.DateTime(timezone=True))
    ends_at=db.Column(db.DateTime(timezone=True))
    status=db.Column(db.String(20),nullable=False,default="DRAFT",index=True)
    attempts_allowed=db.Column(db.Integer,nullable=False,default=1)
    shuffle_questions=db.Column(db.Boolean,default=False,nullable=False)
    shuffle_options=db.Column(db.Boolean,default=False,nullable=False)
    show_results=db.Column(db.Boolean,default=True,nullable=False)
    passing_score=db.Column(db.Float)
    code=db.Column(db.String(32),unique=True,index=True,nullable=False)
    created_at=db.Column(db.DateTime(timezone=True),default=lambda:datetime.now(timezone.utc),nullable=False)
    teacher=db.relationship("User",back_populates="exams")
    questions=db.relationship("ExamQuestion",back_populates="exam",cascade="all, delete-orphan",order_by="ExamQuestion.position")
    attempts=db.relationship("ExamAttempt",back_populates="exam",cascade="all, delete-orphan")

class Question(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    teacher_id=db.Column(db.Integer,db.ForeignKey("user.id"),nullable=False,index=True)
    question_type=db.Column(db.String(20),nullable=False)
    prompt=db.Column(db.Text,nullable=False)
    reference_answer=db.Column(db.Text)
    explanation=db.Column(db.Text)
    default_weight=db.Column(db.Float,nullable=False,default=1)
    created_at=db.Column(db.DateTime(timezone=True),default=lambda:datetime.now(timezone.utc),nullable=False)
    options=db.relationship("QuestionOption",back_populates="question",cascade="all, delete-orphan",order_by="QuestionOption.position")

class QuestionOption(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    question_id=db.Column(db.Integer,db.ForeignKey("question.id"),nullable=False,index=True)
    text=db.Column(db.Text,nullable=False)
    is_correct=db.Column(db.Boolean,nullable=False,default=False)
    position=db.Column(db.Integer,nullable=False,default=0)
    question=db.relationship("Question",back_populates="options")

class ExamQuestion(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    exam_id=db.Column(db.Integer,db.ForeignKey("exam.id"),nullable=False,index=True)
    question_id=db.Column(db.Integer,db.ForeignKey("question.id"),nullable=False,index=True)
    position=db.Column(db.Integer,nullable=False)
    weight=db.Column(db.Float,nullable=False,default=1)
    prompt_snapshot=db.Column(db.Text,nullable=False)
    type_snapshot=db.Column(db.String(20),nullable=False)
    options_snapshot=db.Column(db.JSON,nullable=False,default=list)
    reference_answer_snapshot=db.Column(db.Text)
    exam=db.relationship("Exam",back_populates="questions")
    question=db.relationship("Question")

class ExamAttempt(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    exam_id=db.Column(db.Integer,db.ForeignKey("exam.id"),nullable=False,index=True)
    participant_name=db.Column(db.String(150),nullable=False)
    participant_identity=db.Column(db.String(150),nullable=False)
    started_at=db.Column(db.DateTime(timezone=True),default=lambda:datetime.now(timezone.utc),nullable=False)
    submitted_at=db.Column(db.DateTime(timezone=True))
    status=db.Column(db.String(20),nullable=False,default="IN_PROGRESS",index=True)
    total_score=db.Column(db.Float)
    max_score=db.Column(db.Float)
    grading_complete=db.Column(db.Boolean,nullable=False,default=False)
    exam=db.relationship("Exam",back_populates="attempts")
    answers=db.relationship("StudentAnswer",back_populates="attempt",cascade="all, delete-orphan")

class StudentAnswer(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    attempt_id=db.Column(db.Integer,db.ForeignKey("exam_attempt.id"),nullable=False,index=True)
    exam_question_id=db.Column(db.Integer,db.ForeignKey("exam_question.id"),nullable=False,index=True)
    answer_text=db.Column(db.Text)
    selected_option_id=db.Column(db.Integer)
    auto_score=db.Column(db.Float)
    manual_score=db.Column(db.Float)
    manual_note=db.Column(db.Text)
    graded_at=db.Column(db.DateTime(timezone=True))
    attempt=db.relationship("ExamAttempt",back_populates="answers")
    exam_question=db.relationship("ExamQuestion")
